"""
Evaluator for evolving a GPU kernel for one KernelBench problem (issue #29).

A candidate is a Python file defining ``ModelNew``, a drop-in for the
problem's reference ``Model`` whose work is done by CUDA (``load_inline``) or
Triton kernels. The score is relative to the strongest PyTorch baseline:

    combined_score = bar_ms / candidate_ms

where bar_ms is the fastest of eager, torch.compile(mode="default") and
torch.compile(mode="max-autotune"), timed in the same process as the candidate
(``eval_kb.py``). > 1 means faster than anything PyTorch does on its own.

A candidate scores 0 if:
- it fails KernelBench's static checker (``kernel_static_checker.py`` at the
  pinned commit) with these checks as errors: code bypass (try/except, pass),
  timing patches, thread or stream injection, lazy evaluation, PyTorch compute
  ops or torch.nn modules doing the work, precision downgrade, and no CUDA or
  Triton kernel; or it mentions torch.compile, dynamo, inductor, private
  ``torch._`` APIs or TF32;
- its output differs from the reference on any of 3 fresh random input sets,
  it modifies its inputs, its output aliases an input, or it returns a stale
  result for new inputs;
- it fails to load or compile, or the GPU run fails or times out.

Evaluation runs on a GPU host over SSH, in a container with no network and
only the work directory mounted. Run ``prepare.py`` first. Environment:

    KB_PROBLEM      problem, e.g. level2/12_Gemm_Multiply_LeakyReLU (required)
    KB_HOST         ssh target of the GPU host (required), e.g. ceres.local
    KB_REMOTE_DIR   work directory on the host (default: oeb-kernelbench, under ~)
    KB_IMAGE        container (default: pytorch/pytorch:2.9.1-cuda12.8-cudnn9-devel)
    KB_TIMEOUT      seconds per evaluation (default: 900)
    KB_HOME         local cache (default: examples/kernelbench/.cache)
"""

from __future__ import annotations

import importlib.util
import json
import os
import re
import shlex
import subprocess
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
KERNELBENCH_COMMIT = "423217d9fda91e0c2d67e4a43bf62f96f6d104f1"
IMAGE = "pytorch/pytorch:2.9.1-cuda12.8-cudnn9-devel"
FORBIDDEN = ["code_bypass", "timing_event_patch", "thread_injection", "lazy_eval", "stream_injection",
             "torch_computation_ops", "pytorch_wrap", "precision_downgrade"]
# Beyond KernelBench's checker: PyTorch's own compilers, private torch APIs, process escapes, and TF32
# (fits within the 1e-2 tolerance but is a precision downgrade).
EXTRA_FORBIDDEN = re.compile(r"torch\.compile|_dynamo|_inductor|torch\._|\bimportlib\b|\bsubprocess\b|\bos\.system\b"
                             r"|tf32|float32_matmul_precision", re.IGNORECASE)


def home() -> Path:
    return Path(os.environ.get("KB_HOME", HERE / ".cache"))


def problem() -> str:
    p = os.environ.get("KB_PROBLEM")
    if not p:
        raise RuntimeError("set KB_PROBLEM, e.g. level2/12_Gemm_Multiply_LeakyReLU")
    return p


def host() -> str:
    h = os.environ.get("KB_HOST")
    if not h:
        raise RuntimeError("set KB_HOST to the GPU host's ssh target, e.g. ceres.local")
    return h


def remote_dir() -> str:
    return os.environ.get("KB_REMOTE_DIR", "oeb-kernelbench")


def _checker():
    spec = importlib.util.spec_from_file_location("kernel_static_checker", home() / "kernel_static_checker.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check_source(code: str) -> str | None:
    """Reason the candidate is rejected before it reaches the GPU, or None."""
    chk = _checker()
    m = EXTRA_FORBIDDEN.search(chk._strip_comments(code))
    if m:
        return f"{m.group(0)!r} is not allowed: the kernel must be written, not generated by PyTorch"
    if "class ModelNew" not in code:
        return "the program must define class ModelNew"
    errors = None
    for backend in ("cuda", "triton"):
        valid, errs, _ = chk.validate_kernel_static(code, backend=backend, precision="fp32", forbidden=FORBIDDEN,
                                                    warnings=[])
        if valid:
            return None
        errors = errs if errors is None else errors
    return "static check: " + "; ".join(errors)[:1500]


def ssh(cmd: str, timeout: float, stdin: str | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15", host(), cmd], input=stdin,
                          capture_output=True, text=True, timeout=timeout)


def run_remote(code: str) -> dict:
    name = f"cand-{uuid.uuid4().hex[:12]}.py"
    d = remote_dir()
    image = os.environ.get("KB_IMAGE", IMAGE)
    prob = f"problems/{problem().replace('/', '_')}.py"
    run = (f"cd ~/{d} && cat > cand/{name} && "
           f"timeout {int(os.environ.get('KB_TIMEOUT', 900))} docker run --rm --gpus all --ipc=host --network none "
           f"-u $(id -u):$(id -g) -e HOME=/tmp -e USER=oeb -e LOGNAME=oeb -v $PWD:$PWD -w $PWD {shlex.quote(image)} "
           f"python eval_kb.py {prob} cand/{name} out/{name}.json >/dev/null 2>out/{name}.err; "
           f"cat out/{name}.json 2>/dev/null || tail -c 1500 out/{name}.err; rm -f cand/{name}")
    p = ssh(run, timeout=int(os.environ.get("KB_TIMEOUT", 900)) + 120, stdin=code)
    line = next((l for l in reversed(p.stdout.splitlines()) if l.startswith("{")), None)
    if line is None:
        return {"correct": False, "error": f"GPU run gave no result: {(p.stdout + p.stderr).strip()[-800:]}"}
    return json.loads(line)


def evaluate(program_path: str) -> dict:
    code = Path(program_path).read_text()
    reason = check_source(code)
    if reason:
        return {"combined_score": 0.0, "error": reason}
    try:
        r = run_remote(code)
    except subprocess.TimeoutExpired:
        return {"combined_score": 0.0, "error": "GPU run timed out"}
    if not r.get("correct"):
        return {"combined_score": 0.0, "error": r.get("error", "incorrect")}
    keys = ("speedup_vs_bar", "speedup_vs_eager", "candidate_ms", "bar_best_ms", "load_s", "eval_s")
    out = {"combined_score": r["speedup_vs_bar"], **{k: r[k] for k in keys if k in r}}
    out["bar"] = {"eager": 0, "default": 1, "max-autotune": 2}.get(r.get("bar"), -1)   # numeric for OpenEvolve
    return out


def evaluate_stage1(program_path: str) -> dict:
    """No GPU: the static check alone, so non-kernels are rejected in milliseconds."""
    reason = check_source(Path(program_path).read_text())
    return {"combined_score": 0.0, "error": reason} if reason else {"combined_score": 1.0}


def evaluate_stage2(program_path: str) -> dict:
    return evaluate(program_path)
